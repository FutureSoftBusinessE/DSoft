class InfoTributaria:

    def __init__(self):
        self.ambiente = ""
        self.tipoEmision = ""
        self.razonSocial = ""
        self.nombreComercial = ""
        self.ruc = ""
        self.claveAcceso = ""
        self.codDoc = ""
        self.estab = ""
        self.ptoEmi = ""
        self.secuencial = ""
        self.dirMatriz = ""
        self.agenteRetencion = ""
        self.contribuyenteRimpe = ""

    def getAmbiente(self):
        return self.ambiente

    def setAmbiente(self, ambiente):
        self.ambiente = ambiente

    def getTipoEmision(self):
        return self.tipoEmision

    def setTipoEmision(self, tipoEmision):
        self.tipoEmision = tipoEmision

    def getRazonSocial(self):
        return self.razonSocial

    def setRazonSocial(self, razonSocial):
        self.razonSocial = razonSocial

    def getNombreComercial(self):
        return self.nombreComercial

    def setNombreComercial(self, nombreComercial):
        self.nombreComercial = nombreComercial

    def getRuc(self):
        return self.ruc

    def setRuc(self, ruc):
        self.ruc = ruc

    def getClaveAcceso(self):
        return self.claveAcceso

    def setClaveAcceso(self, claveAcceso):
        self.claveAcceso = claveAcceso

    def getCodDoc(self):
        return self.codDoc

    def setCodDoc(self, codDoc):
        self.codDoc = codDoc

    def getEstab(self):
        return self.estab

    def setEstab(self, estab):
        self.estab = estab

    def getPtoEmi(self):
        return self.ptoEmi

    def setPtoEmi(self, ptoEmi):
        self.ptoEmi = ptoEmi

    def getSecuencial(self):
        return self.secuencial

    def setSecuencial(self, secuencial):
        self.secuencial = secuencial

    def getDirMatriz(self):
        return self.dirMatriz

    def setDirMatriz(self, dirMatriz):
        self.dirMatriz = dirMatriz

    def getAgenteRetencion(self):
        return self.agenteRetencion

    def setAgenteRetencion(self, agenteRetencion):
        self.agenteRetencion = agenteRetencion

    def getContribuyenteRimpe(self):
        return self.contribuyenteRimpe

    def setContribuyenteRimpe(self, contribuyenteRimpe):
        self.contribuyenteRimpe = contribuyenteRimpe
